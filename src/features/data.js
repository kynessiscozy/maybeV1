  // 给一个 seedSet 打分：它对应主题的关键词在输入里命中得越多，分越高
  function scoreSeedSet(text, setKey) {
    var theme = THEMES[SEED_SET_THEME[setKey]];
    if (!theme) return 0;
    return theme.keywords.reduce(function (sum, k) {
      return sum + (text.indexOf(String(k).toLowerCase()) > -1 ? k.length : 0);
    }, 0);
  }

  // 从全部念头里挑出与输入最贴近的若干条。
  // 没命中任何关键词时返回空数组——由调用方决定回退成什么，
  // 而不是在这里塞一个「默认推荐」，那样会把「不认识」伪装成「推荐」。
  function seedsMatching(idea, limit) {
    var text = String(idea || '').toLowerCase();
    if (text.replace(/\s/g, '').length < 2) return [];

    var n = limit || 3;
    var scored = [];
    Object.keys(SEED_SETS).forEach(function (setKey) {
      var setScore = scoreSeedSet(text, setKey);
      if (!setScore) return;
      SEED_SETS[setKey].forEach(function (seed) {
        // 念头自身的文字也参与打分：用户可能直接打出了某条建议的片段。
        // 与主题分相加，让「我打字的内容」和「这条念头本身像不像」一起决定排序。
        var selfHit = 0;
        var label = String(seed.label).toLowerCase();
        var ideaText = String(seed.idea).toLowerCase();
        if (text.length >= 2) {
          if (label.indexOf(text) > -1 || text.indexOf(label) > -1) selfHit += 6;
        }
        var overlap = 0;
        for (var i = 2; i <= 4 && i <= text.length; i++) {
          if (ideaText.indexOf(text.slice(0, i)) > -1) { overlap = i; break; }
        }
        scored.push({ seed: seed, score: setScore + selfHit + overlap, set: setKey });
      });
    });

    scored.sort(function (a, b) { return b.score - a.score; });

    // 同一个 seedSet 里最多取两条，避免三条建议全来自一个主题，
    // 那样看起来不像「几个方向」而像「一个方向的三种说法」。
    var out = [];
    var perSet = {};
    for (var j = 0; j < scored.length && out.length < n; j++) {
      var key = scored[j].set;
      perSet[key] = perSet[key] || 0;
      if (perSet[key] >= 2) continue;
      perSet[key]++;
      out.push(scored[j].seed);
    }
    return out;
  }

